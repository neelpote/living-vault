import solc from 'solc';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const names = ['MockUSDC', 'VaultRenderer', 'LivingVault', 'F1LivingArt', 'test/HostileToken'];
const sources = Object.fromEntries(names.map(name => [`contracts/${name}.sol`, { content: readFileSync(`contracts/${name}.sol`, 'utf8') }]));
const input = { language: 'Solidity', sources, settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: 'osaka', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'metadata'] } } } };
const output = JSON.parse(solc.compile(JSON.stringify(input), { import: name => {
  try { return { contents: readFileSync(path.resolve(name.startsWith('@') ? `node_modules/${name}` : name), 'utf8') }; }
  catch { return { error: `Missing import: ${name}` }; }
} }));
for (const e of output.errors ?? []) console[e.severity === 'error' ? 'error' : 'warn'](e.formattedMessage);
if (output.errors?.some(e => e.severity === 'error')) process.exit(1);
mkdirSync('artifacts', { recursive: true });
mkdirSync('lib/generated', { recursive: true });
mkdirSync('public/deploy', { recursive: true });
for (const name of ['MockUSDC', 'LivingVault', 'F1LivingArt', 'HostileToken']) {
  const sourceName = `contracts/${name === 'HostileToken' ? 'test/' : ''}${name}.sol`;
  const contract = output.contracts[sourceName][name];
  const artifact = { contractName: name, sourceName: `contracts/${name}.sol`, compilerVersion: solc.version(), abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}`, deployedBytecode: `0x${contract.evm.deployedBytecode.object}`, metadata: JSON.parse(contract.metadata) };
  writeFileSync(`artifacts/${name}.json`, JSON.stringify(artifact, null, 2));
  if (name !== 'HostileToken') {
    writeFileSync(`public/deploy/${name}.json`, JSON.stringify({ abi: artifact.abi, bytecode: artifact.bytecode }));
    writeFileSync(`lib/generated/${name}.ts`, `// Generated by npm run contracts:compile.\nexport const ${name === 'LivingVault' ? 'vaultAbi' : name === 'F1LivingArt' ? 'f1Abi' : 'tokenAbi'} = ${JSON.stringify(contract.abi)} as const;\n`);
  }
  console.log(`${name}: ${contract.evm.deployedBytecode.object.length / 2} runtime bytes`);
}
// Include imported sources verbatim so verification needs no network-resolved imports.
const resolved = { ...sources };
for (const [name] of Object.entries(output.sources)) if (!resolved[name]) resolved[name] = { content: readFileSync(path.resolve(`node_modules/${name}`), 'utf8') };
writeFileSync('artifacts/standard-input.json', JSON.stringify({ ...input, sources: resolved }));
