import solc from 'solc';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';

// Separate compilation preserves the original deployed contracts' artifacts.
const sources={'contracts/NativeLivingVault.sol':{content:readFileSync('contracts/NativeLivingVault.sol','utf8')}};
if(process.argv.includes('--tests'))sources['contracts/test/NativeReceiver.sol']={content:readFileSync('contracts/test/NativeReceiver.sol','utf8')};
const input={language:'Solidity',sources,settings:{optimizer:{enabled:true,runs:200},viaIR:true,evmVersion:'osaka',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object','metadata']}}}};
solc.compile(JSON.stringify(input),{import:name=>{
  try{const content=readFileSync(name.startsWith('@')?`node_modules/${name}`:name,'utf8');sources[name]={content};return {contents:content};}
  catch{return {error:`Missing import: ${name}`};}
}});
const output=JSON.parse(solc.compile(JSON.stringify(input)));
for(const e of output.errors??[])console[e.severity==='error'?'error':'warn'](e.formattedMessage);
if(output.errors?.some(e=>e.severity==='error'))process.exit(1);
for(const [source,contracts] of Object.entries(output.contracts))for(const [name,c] of Object.entries(contracts)){
  if(!['NativeLivingVault','NativeReceiver'].includes(name))continue;
  const artifact={contractName:name,sourceName:source,compilerVersion:solc.version(),abi:c.abi,bytecode:`0x${c.evm.bytecode.object}`,deployedBytecode:`0x${c.evm.deployedBytecode.object}`,metadata:JSON.parse(c.metadata)};
  mkdirSync('artifacts',{recursive:true});writeFileSync(`artifacts/${name}.json`,JSON.stringify(artifact,null,2));
  if(name==='NativeLivingVault'){
    mkdirSync('public/deploy',{recursive:true});mkdirSync('lib/generated',{recursive:true});
    writeFileSync('public/deploy/NativeLivingVault.json',JSON.stringify({abi:artifact.abi,bytecode:artifact.bytecode,deployedBytecode:artifact.deployedBytecode}));
    writeFileSync('lib/generated/NativeLivingVault.ts',`// Generated by npm run native:compile.\nexport const nativeVaultAbi = ${JSON.stringify(c.abi)} as const;\n`);
  }
  console.log(`${name}: ${c.evm.deployedBytecode.object.length/2} runtime bytes`);
}
if(!process.argv.includes('--tests'))writeFileSync('artifacts/native-standard-input.json',JSON.stringify(input));
